"""Dump what one camera actually supports, as committed reference.

The CCAPI reference PDF documents the protocol, not any particular body.
Real cameras differ from it - the EOS R100 offers JPEG qualities
small1_fine / small1_normal / small2 where the reference example shows a
plain "small", and it rejects calls the reference lists as available. So
record what the hardware says rather than what the spec says.

    python tools/dump_capabilities.py 192.168.178.212:8080

Writes docs/capabilities/<model>-fw<version>.{json,md}.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys
import urllib.error
import urllib.request

TIMEOUT = 8

# Endpoint families worth recording the current value + allowed values for.
# Deliberately excludes liveview, contents and event: those are stateful or
# huge, and polling them here would disturb a camera in use.
SETTING_PREFIXES = (
    "/shooting/settings/",
    "/shooting/information/",
    "/functions/",
    "/devicestatus/",
)
SKIP = ("/functions/cardformat", "/functions/wificonnection", "/functions/wifisetting")


def get(url: str):
    try:
        with urllib.request.urlopen(url, timeout=TIMEOUT) as resp:
            if resp.status != 200:
                return None, f"HTTP {resp.status}"
            return json.loads(resp.read().decode()), None
    except urllib.error.HTTPError as exc:
        return None, f"HTTP {exc.code}"
    except Exception as exc:  # noqa: BLE001 - reporting, not handling
        return None, type(exc).__name__


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    host = sys.argv[1]
    base = f"http://{host}"

    manifest, err = get(f"{base}/ccapi")
    if err:
        print(f"cannot reach {base}/ccapi: {err}", file=sys.stderr)
        return 1

    info, _ = get(f"{base}/ccapi/ver100/deviceinformation")
    info = info or {}
    model = info.get("productname", "unknown")
    fw = info.get("firmwareversion", "unknown")

    # path -> {version, get/post/put/delete}
    endpoints: dict[str, dict] = {}
    for version, eps in manifest.items():
        if not isinstance(eps, list):
            continue
        for ep in eps:
            path = ep.get("path") or ep.get("url") or ""
            path = re.sub(r"^https?://[^/]+", "", path)
            short = re.sub(r"^/ccapi/ver\d+", "", path)
            endpoints[short] = {
                "version": version,
                "url": path,
                "get": bool(ep.get("get")),
                "post": bool(ep.get("post")),
                "put": bool(ep.get("put")),
                "delete": bool(ep.get("delete")),
            }

    settings: dict[str, dict] = {}
    for short, meta in sorted(endpoints.items()):
        if not meta["get"] or not short.startswith(SETTING_PREFIXES):
            continue
        if short in SKIP:
            continue
        body, err = get(f"{base}{meta['url']}")
        settings[short] = {"error": err} if err else body

    out = {
        "device": info,
        "endpoints": endpoints,
        "settings": settings,
    }

    slug = re.sub(r"[^a-z0-9]+", "-", model.lower()).strip("-")
    outdir = pathlib.Path(__file__).resolve().parent.parent / "docs" / "capabilities"
    outdir.mkdir(parents=True, exist_ok=True)
    # Not Path.with_suffix: firmware versions contain dots, so it would
    # replace ".0" instead of appending.
    stem = f"{slug}-fw{fw}"

    (outdir / f"{stem}.json").write_text(json.dumps(out, indent=2, sort_keys=True) + "\n")
    (outdir / f"{stem}.md").write_text(render_md(out))
    print(f"wrote {outdir}/{stem}.json and {stem}.md")
    print(f"  {len(endpoints)} endpoints, {len(settings)} settings read")
    return 0


def render_md(out: dict) -> str:
    info = out["device"]
    lines = [
        f"# {info.get('productname', 'Unknown camera')} - CCAPI capabilities",
        "",
        f"- Manufacturer: `{info.get('manufacturer', '?')}`",
        f"- Firmware: `{info.get('firmwareversion', '?')}`",
        "",
        "Generated by `tools/dump_capabilities.py` from the camera itself.",
        "This records what **this body** supports, which is not always what the",
        "CCAPI reference describes - check here before assuming an endpoint or",
        "a setting value exists.",
        "",
        "## Settings",
        "",
        "Current value and the values the camera reports as allowed.",
        "",
        "| Setting | Value | Allowed |",
        "|---|---|---|",
    ]
    for path, body in sorted(out["settings"].items()):
        if not isinstance(body, dict) or "error" in body:
            reason = body.get("error", "?") if isinstance(body, dict) else "?"
            lines.append(f"| `{path}` | - | _{reason}_ |")
            continue
        value = body.get("value", body)
        ability = body.get("ability")
        if isinstance(ability, list):
            allowed = ", ".join(f"`{a}`" for a in ability)
        elif isinstance(ability, dict):
            allowed = "<br>".join(
                f"`{k}`: " + (", ".join(f"`{v}`" for v in vals) if isinstance(vals, list) else f"`{vals}`")
                for k, vals in ability.items()
            )
        else:
            allowed = "-"
        lines.append(f"| `{path}` | `{json.dumps(value)}` | {allowed or '-'} |")

    lines += ["", "## Endpoints", "", "| Endpoint | Ver | GET | POST | PUT | DELETE |", "|---|---|---|---|---|---|"]
    tick = {True: "O", False: "-"}
    for path, meta in sorted(out["endpoints"].items()):
        lines.append(
            f"| `{path}` | {meta['version']} | {tick[meta['get']]} | "
            f"{tick[meta['post']]} | {tick[meta['put']]} | {tick[meta['delete']]} |"
        )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    raise SystemExit(main())
